#!/usr/bin/env bash
#
# Regenerates scripts/test-shards.txt by assigning integration tests to shards
# with a greedy longest-first balance. Run it after adding, renaming or
# removing a test in tests/integration; scripts/test-shard.sh fails when a test
# has no assignment, so a stale manifest cannot silently skip coverage.
#
# Usage: scripts/balance-test-shards.sh [shard-count]   (default 4)
# See docs/04-ui-and-cli-specification.md section 6.

set -euo pipefail

cd "$(dirname "$0")/.."

TOTAL="${1:-4}"
MANIFEST="scripts/test-shards.txt"

printf 'measuring %s...\n' "tests/integration" >&2
# Durations come from the verbose run; a cached result would report no time, so
# the run is forced with -count=1.
measure_log="$(mktemp)"
trap 'rm -f "$measure_log"' EXIT
go test ./tests/integration -count=1 -v >"$measure_log" 2>&1 || true

{
  printf '# Integration test shard assignment, generated by\n'
  printf '# scripts/balance-test-shards.sh. Format: <test-name> <shard>.\n'
  printf '# Regenerate after adding, renaming or removing an integration test.\n'
} >"$MANIFEST"

# Greedy longest-first assignment: the heaviest remaining test always goes to
# the shard with the least accumulated time.
awk '
  /^--- (PASS|FAIL): / {
    name = $3
    duration = $4
    gsub(/[()]/, "", duration)
    sub(/s$/, "", duration)
    printf "%s %s\n", name, duration
  }
' "$measure_log" >"$measure_log.times"

if [ ! -s "$measure_log.times" ]; then
  printf 'error: no test timings were captured; run `make ui` first if web/dist is missing\n' >&2
  rm -f "$measure_log.times"
  exit 1
fi

sort -k2 -gr "$measure_log.times" | awk -v total="$TOTAL" -v manifest="$MANIFEST" '
  BEGIN {
    for (i = 1; i <= total; i++) load[i] = 0
  }
  {
    name = $1; duration = $2 + 0
    best = 1
    for (i = 2; i <= total; i++) if (load[i] < load[best]) best = i
    load[best] += duration
    printf "%s %d\n", name, best >> manifest
    if (duration > 0) assigned++
  }
  END {
    for (i = 1; i <= total; i++) printf "shard %d: %.1fs\n", i, load[i] > "/dev/stderr"
  }
' "$measure_log.times"

rm -f "$measure_log.times"

tests="$(grep -vc '^#' "$MANIFEST" || true)"
printf 'wrote %s (%s tests across %s shards)\n' "$MANIFEST" "$tests" "$TOTAL"
