package server

import (
	"context"
	"net/http"

	"github.com/gray0128/memctl/internal/dream"
	"github.com/gray0128/memctl/internal/memerr"
	"github.com/gray0128/memctl/internal/watcher"
)

// This file implements the Dreaming routes. Stage D-1 added the asynchronous
// preview: the request fixes the baseline and returns the proposal id, and the
// UI follows the status through dream.updated and GET
// /api/v1/dream/{proposalId}. Stage D-2 adds the explicit apply of an
// already-reviewed proposal.

// dreamPreviewBody is the POST /api/v1/dream:preview request.
type dreamPreviewBody struct {
	Runner       string `json:"runner"`
	BaseRevision string `json:"baseRevision"`
}

// dreamPreviewResponse is the 202 response carrying the new proposal id.
type dreamPreviewResponse struct {
	ProposalID string `json:"proposalId"`
}

// dreamApplyBody is the POST /api/v1/dream:apply request. Both fields are
// required so an apply can never reinterpret a changed proposal.
type dreamApplyBody struct {
	ProposalID string `json:"proposalId"`
	PatchHash  string `json:"patchHash"`
}

// handleDreamPreview fixes the baseline under the repository lock, persists a
// generating proposal and starts the isolated runner. The read-only middleware
// already rejects this route when the server runs with --readonly.
func (s *Server) handleDreamPreview(w http.ResponseWriter, r *http.Request) {
	if s.dreamRun != nil {
		select {
		case s.dreamRun <- struct{}{}:
		default:
			s.writeAppError(w, memerr.New(memerr.Busy,
				"another Dreaming generation is already running; retry after it finishes"))
			return
		}
	}
	var body dreamPreviewBody
	if err := decodeBody(r, &body); err != nil {
		s.releaseDreamSlot()
		s.writeAppError(w, err)
		return
	}
	proposal, err := s.app.DreamBegin(r.Context(), body.Runner, body.BaseRevision)
	if err != nil {
		s.releaseDreamSlot()
		s.writeAppError(w, err)
		return
	}
	writeJSONStatus(w, http.StatusAccepted, dreamPreviewResponse{ProposalID: proposal.ProposalID})
	go s.runDream(proposal.ProposalID)
}

// releaseDreamSlot returns one concurrency slot to the generation bound.
func (s *Server) releaseDreamSlot() {
	if s.dreamRun != nil {
		<-s.dreamRun
	}
}

// runDream executes one started generation and publishes the terminal
// dream.updated event. The runner has its own isolation time budget, so the
// background context carries no second deadline.
func (s *Server) runDream(proposalID string) {
	defer s.releaseDreamSlot()
	proposal, err := s.app.DreamRun(context.Background(), proposalID)
	status := proposal.Status
	if err != nil && status == "" {
		status = "failed"
	}
	s.events.Publish(watcher.Invalidation{
		Reason:     watcher.ReasonDreamUpdated,
		ProposalID: proposalID,
		Status:     status,
	})
}

// dreamListResponse is the GET /api/v1/dream body.
type dreamListResponse struct {
	Proposals []dream.Proposal `json:"proposals"`
}

// handleDreamList lists the persisted proposals in createdAt order descending.
// It is a read-only route, so it stays available with --readonly and does not
// depend on the remote readiness of the Actions path. The internal apply input is
// never part of the response.
func (s *Server) handleDreamList(w http.ResponseWriter, r *http.Request) {
	limit, err := intParam(r.URL.Query().Get("limit"))
	if err != nil {
		s.writeAppError(w, err)
		return
	}
	proposals, err := s.app.DreamList(r.Context(), limit)
	if err != nil {
		s.writeAppError(w, err)
		return
	}
	if proposals == nil {
		proposals = []dream.Proposal{}
	}
	writeJSON(w, dreamListResponse{Proposals: proposals})
}

// handleDreamProposal returns one stored proposal. A proposal generated by a
// previous process is reconciled from generating to failed.
func (s *Server) handleDreamProposal(w http.ResponseWriter, r *http.Request) {
	proposal, err := s.app.DreamProposal(r.Context(), r.PathValue("proposalId"))
	if err != nil {
		s.writeAppError(w, err)
		return
	}
	writeJSON(w, proposal)
}

// handleDreamApply commits one already-reviewed proposal through the managed
// transaction and publishes the resulting status. The read-only middleware
// rejects the request before it reaches this handler when --readonly is set.
func (s *Server) handleDreamApply(w http.ResponseWriter, r *http.Request) {
	var body dreamApplyBody
	if err := decodeBody(r, &body); err != nil {
		s.writeAppError(w, err)
		return
	}
	if body.ProposalID == "" || body.PatchHash == "" {
		s.writeAppError(w, memerr.New(memerr.InvalidArgument,
			"proposalId and patchHash are required to apply a proposal"))
		return
	}
	result, err := s.app.ApplyDream(r.Context(), body.ProposalID, body.PatchHash)
	if err != nil {
		s.writeAppError(w, err)
		return
	}
	s.events.Publish(watcher.Invalidation{
		Reason:     watcher.ReasonDreamUpdated,
		ProposalID: body.ProposalID,
		Status:     "applied",
	})
	writeJSON(w, result)
}
